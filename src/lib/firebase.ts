// Defensive payload helpers synchronized with firebase-blueprint.json & firestore.rules
export const SAFE_ID_REGEX = /^[a-zA-Z0-9_-]+$/;
export const SAFE_DATE_REGEX = /^[0-9]{4}-[0-9]{2}-[0-9]{2}$/;

export function createSafeId(prefix: string): string {
  const randomPart = Math.random().toString(36).slice(2, 10);
  const id = `${prefix}_${Date.now()}_${randomPart}`.replace(/[^a-zA-Z0-9_-]/g, '');
  return id.slice(0, 128);
}

export function truncateString(value: string, maxLength: number, fallback = 'Untitled'): string {
  const trimmed = value.trim();
  if (!trimmed) {
    return fallback.slice(0, maxLength);
  }
  return trimmed.slice(0, maxLength);
}

export function clampInteger(value: number, min: number, max: number): number {
  const rounded = Math.round(Number.isFinite(value) ? value : min);
  return Math.max(min, Math.min(max, rounded));
}
